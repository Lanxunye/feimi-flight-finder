"""Dedicated Ctrip browser adapter for Feimi.

The browser runs in a dedicated Chrome profile and exposes CDP only on
localhost. This module never reads or returns cookies, passwords, or form data;
it only captures the structured flight-search response generated by a route
navigation.
"""

from __future__ import annotations

import asyncio
import base64
import hashlib
import json
import os
import urllib.request
from datetime import datetime
from typing import Any


CDP_URL = os.getenv("CTRIP_CDP_URL", "http://127.0.0.1:9223")
SEARCH_RESPONSE_FRAGMENT = "/international/search/api/search/batchSearch"
MAX_TOTAL_MINUTES = 16 * 60
MIN_PROTECTED_THROUGH_TRANSFER_MINUTES = 90
THROUGH_SERVICE_STANDARD = ["一次支付", "一次值机", "一次安检", "行李直挂", "航变保障"]


def ctrip_url(origin: str, destination: str, date: str) -> str:
    return (
        "https://flights.ctrip.com/online/list/oneway-"
        f"{origin.lower()}-{destination.lower()}?depdate={date}"
    )


def cdp_available() -> bool:
    try:
        with urllib.request.urlopen(f"{CDP_URL.rstrip('/')}/json/version", timeout=1.5) as response:
            return response.status == 200
    except Exception:
        return False


class CtripSessionClient:
    """Serializes access to the user's dedicated Ctrip Chrome profile."""

    def __init__(self) -> None:
        self._lock = asyncio.Lock()
        self._playwright: Any = None
        self._browser: Any = None

    async def _connect(self) -> Any:
        if self._browser is not None and self._browser.is_connected():
            return self._browser
        from playwright.async_api import async_playwright

        self._playwright = await async_playwright().start()
        self._browser = await self._playwright.chromium.connect_over_cdp(CDP_URL, timeout=12_000)
        return self._browser

    async def query(self, origin: str, destination: str, date: str) -> dict[str, Any]:
        async with self._lock:
            browser = await self._connect()
            if not browser.contexts:
                raise RuntimeError("Ctrip Chrome profile has no browser context")
            page = await browser.contexts[0].new_page()
            cdp_session = await page.context.new_cdp_session(page)
            try:
                loop = asyncio.get_running_loop()
                captured: asyncio.Future[dict[str, Any]] = loop.create_future()

                async def capture_response(event: dict[str, Any]) -> None:
                    request_id = event["requestId"]
                    try:
                        status = int(event.get("responseStatusCode") or 0)
                        if not 200 <= status < 300:
                            raise RuntimeError(f"Ctrip search returned HTTP {status}")
                        payload = await cdp_session.send("Fetch.getResponseBody", {"requestId": request_id})
                        body = payload["body"]
                        if payload.get("base64Encoded"):
                            body = base64.b64decode(body).decode("utf-8")
                        if not captured.done():
                            captured.set_result(json.loads(body))
                    except Exception as error:
                        if not captured.done():
                            captured.set_exception(error)
                    finally:
                        try:
                            await cdp_session.send("Fetch.continueResponse", {"requestId": request_id})
                        except Exception:
                            pass

                cdp_session.on(
                    "Fetch.requestPaused",
                    lambda event: asyncio.create_task(capture_response(event)),
                )
                await cdp_session.send(
                    "Fetch.enable",
                    {
                        "patterns": [
                            {
                                "urlPattern": f"*{SEARCH_RESPONSE_FRAGMENT}*",
                                "requestStage": "Response",
                            }
                        ]
                    },
                )
                await page.goto(
                    ctrip_url(origin, destination, date),
                    wait_until="domcontentloaded",
                    timeout=60_000,
                )
                return await asyncio.wait_for(captured, timeout=60)
            finally:
                try:
                    await cdp_session.send("Fetch.disable")
                except Exception:
                    pass
                await page.close()


def _parse_datetime(value: Any) -> datetime:
    text = str(value or "").strip().replace("/", "-")
    if not text:
        raise ValueError("missing datetime")
    return datetime.fromisoformat(text.replace("Z", "+00:00"))


def _positive_number(value: Any) -> float | None:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if number > 0 else None


def _fare_total(fare: dict[str, Any]) -> float | None:
    sort_price = _positive_number(fare.get("sortPrice"))
    if sort_price is not None:
        return sort_price
    adult = _positive_number(fare.get("adultPrice"))
    if adult is None:
        return None
    tax = _positive_number(fare.get("adultTax")) or 0
    return adult + tax


def _itinerary_price(itinerary: dict[str, Any]) -> float | None:
    price_lists: list[list[dict[str, Any]]] = []
    if isinstance(itinerary.get("priceList"), list):
        price_lists.append(itinerary["priceList"])
    for group in itinerary.get("flightSegments") or []:
        if isinstance(group.get("priceList"), list):
            price_lists.append(group["priceList"])
    totals = [
        total
        for fares in price_lists
        for fare in fares
        if isinstance(fare, dict) and (total := _fare_total(fare)) is not None
    ]
    return min(totals) if totals else None


def _fare_lists(itinerary: dict[str, Any]) -> list[dict[str, Any]]:
    fares = [fare for fare in itinerary.get("priceList") or [] if isinstance(fare, dict)]
    for group in itinerary.get("flightSegments") or []:
        fares.extend(fare for fare in group.get("priceList") or [] if isinstance(fare, dict))
    return fares


def _nested_text(value: Any) -> str:
    if isinstance(value, dict):
        return "\n".join(_nested_text(child) for child in value.values())
    if isinstance(value, list):
        return "\n".join(_nested_text(child) for child in value)
    return value if isinstance(value, str) else ""


def _itinerary_has_through_label(itinerary: dict[str, Any]) -> bool:
    return any(
        isinstance(tag, dict) and str(tag.get("label") or "").strip() == "通程"
        for tag in itinerary.get("itineraryTags") or []
    )


def _fare_is_explicit_through(fare: dict[str, Any]) -> bool:
    for tag in fare.get("priceTags") or []:
        if not isinstance(tag, dict):
            continue
        data = tag.get("data") if isinstance(tag.get("data"), dict) else {}
        title = str(data.get("tag") or "").strip()
        description = _nested_text(data)
        if title == "通程值机":
            return True
        if all(term in description for term in ("一次支付", "一次值机", "一次安检", "行李直挂", "全程无忧")):
            return True
    return False


def _through_price(itinerary: dict[str, Any]) -> float | None:
    totals = [
        total
        for fare in _fare_lists(itinerary)
        if _fare_is_explicit_through(fare) and (total := _fare_total(fare)) is not None
    ]
    return min(totals) if totals else None


def _station(unit: dict[str, Any], prefix: str, fallback_code: str) -> dict[str, str]:
    code = (
        unit.get(f"{prefix}AirportCode")
        or unit.get(f"{prefix}CityCode")
        or fallback_code
    )
    return {
        "code": str(code).upper(),
        "city": str(unit.get(f"{prefix}CityName") or code),
        "airport": str(
            unit.get(f"{prefix}AirportShortName")
            or unit.get(f"{prefix}AirportName")
            or ""
        ),
    }


def normalize_ctrip_response(
    payload: Any,
    response: dict[str, Any],
    check_name: str,
) -> dict[str, dict[str, Any]]:
    """Normalize Ctrip's batchSearch payload without logging its raw content."""

    checked_at = datetime.now().astimezone().isoformat()
    purchase_url = ctrip_url(payload.origin, payload.destination, payload.date)
    root = response.get("data") if isinstance(response.get("data"), dict) else response
    itineraries = root.get("flightItineraryList") or []
    normalized: dict[str, dict[str, Any]] = {}

    for itinerary in itineraries:
        if not isinstance(itinerary, dict):
            continue
        units = [
            unit
            for group in itinerary.get("flightSegments") or []
            for unit in group.get("flightList") or []
            if isinstance(unit, dict)
        ]
        if not units or len(units) > 2:
            continue
        through_only = bool(getattr(payload, "through_only", False))
        if through_only and len(units) != 2:
            continue
        normal_price = _itinerary_price(itinerary)
        itinerary_through = _itinerary_has_through_label(itinerary)
        through_price = _through_price(itinerary)
        if normal_price is None:
            continue
        if through_only and not itinerary_through and through_price is None:
            continue
        price = through_price if through_only and not itinerary_through else normal_price
        if price is None:
            continue
        selected_is_through = len(units) == 2 and (
            itinerary_through
            or (through_price is not None and abs(through_price - price) < 0.01)
        )
        try:
            departures = [_parse_datetime(unit.get("departureDateTime")) for unit in units]
            arrivals = [_parse_datetime(unit.get("arrivalDateTime")) for unit in units]
        except ValueError:
            continue
        if departures[0].date().isoformat() != payload.date:
            continue
        total_minutes = int((arrivals[-1] - departures[0]).total_seconds() // 60)
        if total_minutes <= 0 or total_minutes > MAX_TOTAL_MINUTES:
            continue

        segments: list[dict[str, Any]] = []
        valid = True
        for index, unit in enumerate(units):
            flight_no = str(
                unit.get("flightNo")
                or unit.get("marketFlightNo")
                or unit.get("operateFlightNo")
                or ""
            ).replace(" ", "")
            if not flight_no:
                valid = False
                break
            from_fallback = payload.origin if index == 0 else ""
            to_fallback = payload.destination if index == len(units) - 1 else ""
            from_station = _station(unit, "departure", from_fallback)
            to_station = _station(unit, "arrival", to_fallback)
            if index == 0:
                from_station["code"] = payload.origin
            if index == len(units) - 1:
                to_station["code"] = payload.destination
            segment_minutes = int((arrivals[index] - departures[index]).total_seconds() // 60)
            if segment_minutes <= 0:
                valid = False
                break
            segments.append(
                {
                    "from": from_station,
                    "to": to_station,
                    "departTime": departures[index].strftime("%H:%M"),
                    "arriveTime": arrivals[index].strftime("%H:%M"),
                    "departDate": departures[index].date().isoformat(),
                    "arriveDate": arrivals[index].date().isoformat(),
                    "flightNo": flight_no,
                    "airline": str(
                        unit.get("marketAirlineName")
                        or unit.get("marketingAirlineName")
                        or unit.get("operateAirlineName")
                        or flight_no[:2]
                    ),
                    "durationMinutes": segment_minutes,
                }
            )
        if not valid:
            continue

        transfer_minutes = None
        if len(segments) == 2:
            transfer_minutes = int((departures[1] - arrivals[0]).total_seconds() // 60)
            minimum_transfer = (
                MIN_PROTECTED_THROUGH_TRANSFER_MINUTES
                if selected_is_through
                else payload.min_transfer_minutes
            )
            if transfer_minutes < minimum_transfer:
                continue
            transfer_code = segments[0]["to"]["code"]
            segments[1]["from"]["code"] = transfer_code
            if payload.transfer and transfer_code != payload.transfer:
                continue
        elif payload.transfer:
            continue

        signature = "|".join(
            f"{segment['flightNo']}@{segment['departDate']}T{segment['departTime']}>{segment['arriveDate']}T{segment['arriveTime']}"
            for segment in segments
        )
        normalized[signature] = {
            "price": price,
            "segments": segments,
            "transferMinutes": transfer_minutes,
            "totalMinutes": total_minutes,
            "crossDay": arrivals[-1].date() != departures[0].date(),
            "throughFlight": selected_is_through,
            "throughServices": THROUGH_SERVICE_STANDARD if selected_is_through else [],
            "purchaseUrl": purchase_url,
            "evidence": {
                "source": f"携程-{check_name}",
                "provider": "携程",
                "checkId": f"ctrip-session-{check_name}",
                "price": price,
                "checkedAt": checked_at,
                "url": purchase_url,
            },
        }
    return normalized


def reconcile_ctrip(
    first: dict[str, dict[str, Any]],
    second: dict[str, dict[str, Any]],
) -> list[dict[str, Any]]:
    offers: list[dict[str, Any]] = []
    for signature, candidate in first.items():
        confirmation = second.get(signature)
        if confirmation is None:
            continue
        same_price = abs(candidate["price"] - confirmation["price"]) < 0.01
        tags = [
            "两次价格一致" if same_price else "价格有变动·请人工选择",
            "专用浏览器实时查询",
            "可跳转购买",
        ]
        if candidate.get("throughFlight"):
            tags = ["通程航班·携程明确标识", "一次值机·行李直挂·航变保障", *tags]
            if candidate.get("transferMinutes", 0) < 120:
                minutes = int(candidate["transferMinutes"])
                tags.insert(2, f"通程保障衔接·{minutes // 60}小时{minutes % 60}分")
        offers.append(
            {
                "id": f"ctrip-session-{hashlib.sha256(signature.encode()).hexdigest()[:16]}",
                "price": confirmation["price"],
                "provider": "携程",
                "tags": tags,
                "segments": candidate["segments"],
                "transferMinutes": candidate["transferMinutes"],
                "totalMinutes": candidate["totalMinutes"],
                "crossDay": candidate["crossDay"],
                "throughFlight": bool(candidate.get("throughFlight")),
                "throughServices": candidate.get("throughServices") or [],
                "purchaseUrl": confirmation["purchaseUrl"],
                "updatedAt": confirmation["evidence"]["checkedAt"],
                "evidence": [candidate["evidence"], confirmation["evidence"]],
                "signature": signature,
            }
        )
    return offers
